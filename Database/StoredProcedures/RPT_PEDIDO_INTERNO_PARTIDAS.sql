	--	SELECT QUOTENAME(talla) + ', '
	--	FROM #TEMP
	--	FOR XML PATH('')
	--);
	--	SELECT (
	--	SELECT QUOTENAME(talla) + ', '
	--	FROM #TEMP T, #PARTIDAS P
	--	WHERE T.CVE_CLIENTE = P.CVE_CLIENTE AND T.CVE_PRENDA = P.CVE_PRENDA AND T.LUGARDEENTREGA = P.LUGARDEENTREGA AND T.FECHAVENCIMIENTO = P.FECHAVENCIMIENTO
	--	GROUP BY T.CVE_CLIENTE,T.CVE_PRENDA,T.LUGARDEENTREGA,T.FECHAVENCIMIENTO,T.PRIORIDAD,T.TALLA
	--	FOR XML PATH('')
	--);
	CREATE TABLE #TEMP2
	(
		CVE_CLIENTE BIGINT,
		CVE_PRENDA BIGINT,
		LUGARDEENTREGA BIGINT,
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		CANTIDAD_TALLAS BIGINT
	)
	INSERT INTO #TEMP2
	(
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		CANTIDAD_TALLAS
	)
	SELECT 
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		COUNT(*) 
	FROM 
		#TEMP 
	GROUP BY 
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD

	CREATE TABLE #TEMP3
	(
		PARTIDA BIGINT,
		CVE_CLIENTE BIGINT,
		CVE_PRENDA BIGINT,
		LUGARDEENTREGA BIGINT,
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		CANT_MAX_TALLAS BIGINT,
		QUERYTALLAS NVARCHAR(MAX)
	)

	SELECT @CANTIDAD_DIFERENTES_TALLAS = MAX(CANTIDAD_TALLAS) FROM #TEMP2

	SELECT @CANTIDAD_DIFERENTES_TALLAS = CEILING(@CANTIDAD_DIFERENTES_TALLAS/13)

	DECLARE @CONTADOR AS INT = 1
	DECLARE @INICIAL AS INT
	DECLARE @FINAL AS INT
	--SELECT * FROM #TEMP
	--SELECT * FROM #PARTIDAS
	--SELECT * FROM #TEMP2
	SET @INICIAL = 1
	SET @FINAL = @INICIAL+12
	WHILE @CONTADOR <= @CANTIDAD_DIFERENTES_TALLAS
	BEGIN
		--select @INICIAL as inicial,@FINAL as final
		INSERT INTO #TEMP3
		(	
			PARTIDA,
			CVE_CLIENTE,
			CVE_PRENDA,
			LUGARDEENTREGA,
			FECHAVENCIMIENTO,
			PRIORIDAD,
			CANT_MAX_TALLAS,
			QUERYTALLAS
		)
		SELECT 
		--@CONTADOR AS PARTIDA,
		P.PARTIDA,
		P.CVE_CLIENTE, 
		P.CVE_PRENDA, 
		P.LUGARDEENTREGA, 
		P.FECHAVENCIMIENTO,
		P.PRIORIDAD,
		(SELECT COUNT(*) FROM #TEMP T1 WHERE T1.CVE_CLIENTE = P.CVE_CLIENTE AND T1.CVE_PRENDA = P.CVE_PRENDA AND T1.LUGARDEENTREGA = P.LUGARDEENTREGA AND T1.FECHAVENCIMIENTO = P.FECHAVENCIMIENTO AND T1.PRIORIDAD = P.PRIORIDAD AND T1.CONSECUTIVO1 >= @INICIAL AND T1.CONSECUTIVO1 <=@FINAL),---ESTO ES PARA QUE ME SUME LA CANTIDAD DE TALLAS QUE ESTA METIENDO EN ESA PARTIDA PARA USAR EN EL RELLENO
		--T2.CANTIDAD_TALLAS,---ESTO SE SUSTITUYO POR LA LINEA DE ARRIBA
		(SELECT QUOTENAME(T.talla) + ', '
		--(SELECT T.talla + ', '
		 FROM #TEMP T
		 WHERE T.CVE_CLIENTE = P.CVE_CLIENTE AND T.CVE_PRENDA = P.CVE_PRENDA AND T.LUGARDEENTREGA = P.LUGARDEENTREGA AND T.FECHAVENCIMIENTO = P.FECHAVENCIMIENTO AND T.PRIORIDAD = P.PRIORIDAD AND T.CONSECUTIVO1 >= @INICIAL AND T.CONSECUTIVO1 <=@FINAL
		 GROUP BY T.CVE_CLIENTE, T.CVE_PRENDA, T.LUGARDEENTREGA, T.FECHAVENCIMIENTO, T.PRIORIDAD, T.TALLA,T.PARTIDA
		 ORDER BY T.PARTIDA
		 FOR XML PATH('')
		) AS Tallas
		FROM #PARTIDAS P,
			#TEMP2 T2
		WHERE
			T2.CVE_CLIENTE = P.CVE_CLIENTE AND T2.CVE_PRENDA = P.CVE_PRENDA AND T2.LUGARDEENTREGA = P.LUGARDEENTREGA AND T2.FECHAVENCIMIENTO = P.FECHAVENCIMIENTO AND T2.PRIORIDAD = P.PRIORIDAD
		--GROUP BY 
		--	P.PARTIDA,
		--	P.CVE_CLIENTE, 
		--	P.CVE_PRENDA, 
		--	P.LUGARDEENTREGA, 
		--	P.FECHAVENCIMIENTO,
		--	P.PRIORIDAD

		SET @INICIAL = @FINAL+1
		SET @FINAL = @INICIAL+12
	
		SET @CONTADOR+=1
	END
	
	DELETE #TEMP3 WHERE QUERYTALLAS IS NULL
	--SELECT * FROM #TEMP3
	UPDATE
		#TEMP3
	SET	
		QUERYTALLAS = QUERYTALLAS + R.RELLENO--REPLICATE(QUOTENAME('NULL') + ', ',13-CANT_MAX_TALLAS) 
	FROM
		#TEMP3 T,
		#RELLENO R
	WHERE
		CANT_MAX_TALLAS < 13
	AND R.CONSECUTIVO = 13-CANT_MAX_TALLAS

	UPDATE
		#TEMP3
	SET	
		QUERYTALLAS = QUERYTALLAS + R.RELLENO --REPLICATE(QUOTENAME('NULL') + ', ',13-(CANT_MAX_TALLAS-13)) 
	FROM
		#TEMP3 T,
		#RELLENO R
	WHERE
		T.CANT_MAX_TALLAS > 13
	AND T.PARTIDA = CEILING(CONVERT(DECIMAL,CANT_MAX_TALLAS)/13)
	AND R.CONSECUTIVO = 13-(CANT_MAX_TALLAS-13)


	UPDATE
		#TEMP3
	SET	QUERYTALLAS = LEFT(QUERYTALLAS, LEN(QUERYTALLAS) - 1) FROM #TEMP3

	--SELECT * FROM #TEMP
	--SELECT * FROM #TEMP2
	--SELECT * FROM #TEMP3

	DECLARE 
		@PARTIDA_CURSOR BIGINT,
		@CVE_CLIENTE_CURSOR BIGINT,
		@CVE_PRENDA_CURSOR BIGINT,
		@LUGARDEENTREGA_CURSOR BIGINT,
		@FECHAVENCIMIENTO_CURSOR DATE,
		@PRIORIDAD_CURSOR BIGINT,
		@CANT_MAX_TALLAS_CURSOR BIGINT,
		@QUERYTALLAS NVARCHAR(MAX),
		@PARTIDA_ANTERIOR AS BIGINT,
		@CONSECUTIVOPARTIDA AS BIGINT

	SET @PARTIDA_ANTERIOR = 0
	SET @CONSECUTIVOPARTIDA = 0

	DECLARE PARTIDASPEDIDO CURSOR FOR
	SELECT
		PARTIDA,
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		CANT_MAX_TALLAS,
		QUERYTALLAS
	FROM
		#TEMP3
	ORDER BY
		PARTIDA
	OPEN PARTIDASPEDIDO
	FETCH NEXT FROM PARTIDASPEDIDO INTO @PARTIDA_CURSOR,@CVE_CLIENTE_CURSOR,@CVE_PRENDA_CURSOR,@LUGARDEENTREGA_CURSOR,@FECHAVENCIMIENTO_CURSOR,@PRIORIDAD_CURSOR,@CANT_MAX_TALLAS_CURSOR,@QUERYTALLAS
	WHILE @@FETCH_STATUS = 0
	BEGIN
		IF @PARTIDA_ANTERIOR = @PARTIDA_CURSOR
		BEGIN
			SET @CONSECUTIVOPARTIDA +=1
		END
		ELSE
		BEGIN
			SET @CONSECUTIVOPARTIDA = 1
		END
		--SELECT @CONSECUTIVOPARTIDA,@PARTIDA_CURSOR
		SET @sql = 'SELECT 
			  NO_PEDIDO,
			  CVE_PRENDA,
			  DESCRIPCIONPRENDA,
			  TELABASE,
			  TELACOMBINACION,
			  LOGOTIPOS,
			  LUGARDEENTREGA,
			  NOMBRELUGARDEENTREGA,
			  FECHAVENCIMIENTO,
			  PRIORIDAD,
			  MOTIVOPRIORIDAD,
			  PARTIDA,
			  ' + CONVERT(nvarchar,@CONSECUTIVOPARTIDA) + ',
			  ' + @QUERYTALLAS + ',
			  PRECIO,
			  PORCENTAJE_IVA,
			  OBSERVACIONES_PARTIDAPRODUCCION,
			  OBSERVACIONES_PARTIDALOGISTICA,
			  OBSERVACIONES_PARTIDAFACTURACION
			FROM 
			(
			  SELECT 
				NO_PEDIDO,
				CVE_PRENDA,
				DESCRIPCIONPRENDA,
				TELABASE,
				TELACOMBINACION,
				LOGOTIPOS,
				LUGARDEENTREGA,
				NOMBRELUGARDEENTREGA,
				FECHAVENCIMIENTO,
				PRIORIDAD,
				MOTIVOPRIORIDAD,
				PARTIDA,
				talla AS talla_column,
				MAX(TALLA) AS TALLA_total,
				PRECIO,
				PORCENTAJE_IVA,
				OBSERVACIONES_PARTIDAPRODUCCION,
				OBSERVACIONES_PARTIDALOGISTICA,
				OBSERVACIONES_PARTIDAFACTURACION
