		(
			SELECT ', ' + CONVERT(NVARCHAR, PEMD.Cve_Tela) + ' (' + CT.Composicion + ')'
			FROM PRENDA_ESTRUCTURA_MATERIALES_DETALLE PEMD,CATALOGO_TELA CT
			WHERE PEMD.Cve_Prenda = PIT.Cve_Prenda AND PEMD.TipoMaterial = 'T' AND PEMD.TipoTela = 'B' AND CT.Cve_Tela = PEMD.Cve_Tela
			GROUP BY PEMD.Cve_Tela,CT.Composicion
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS TelaBase,
		STUFF(
		(
			SELECT ', ' + CONVERT(NVARCHAR, PEMD.Cve_Tela) + ' (' + CT.Composicion + ')'
			FROM PRENDA_ESTRUCTURA_MATERIALES_DETALLE PEMD,CATALOGO_TELA CT
			WHERE PEMD.Cve_Prenda = PIT.Cve_Prenda AND PEMD.TipoMaterial = 'T' AND PEMD.TipoTela = 'C' AND CT.Cve_Tela = PEMD.Cve_Tela
			GROUP BY PEMD.Cve_Tela,CT.Composicion
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS TelaCombinacion,
		STUFF(
		(
			SELECT ', ' + CONVERT(NVARCHAR, PL.Cve_Logotipo) 
			FROM PRENDA_LOGOTIPO PL 
			WHERE PL.Cve_Prenda = PIT.Cve_Prenda
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS Logotipos
	FROM 
		PEDIDO_INTERNO PI,
		PEDIDO_INTERNO_TALLAS PIT
	WHERE 
		PI.Empresa = @EMPRESA
		AND PI.No_Pedido = @NO_PEDIDO
		AND PIT.Empresa = PI.Empresa
		AND PIT.No_Pedido = PI.No_Pedido
	GROUP BY
		PI.Cve_Cliente,
		PIT.Cve_Prenda,
		PIT.LugarDeEntrega,
		PIT.Partida,
		CONVERT(DATE,PIT.FechaVencimiento),
		PIT.Prioridad
		--select * from #PARTIDAS
	CREATE TABLE #TEMP
	(
		CVE_CLIENTE BIGINT,
		CVE_PRENDA BIGINT,
		LUGARDEENTREGA BIGINT,
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		CONSECUTIVO BIGINT,--ESTE SE UTILIZA COMO NÚMERO DE PARTIDA
		CONSECUTIVO1 BIGINT,--ESTE SE UTILIZA COMO CONSECUTIVO DE TALLA
		TELABASE NVARCHAR(MAX),
		TELACOMBINACION NVARCHAR(MAX),
		LOGOTIPOS NVARCHAR(MAX),
		PARTIDA BIGINT,
		TALLA NVARCHAR(50)
	)

	INSERT INTO #TEMP
	(
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		CONSECUTIVO,
		CONSECUTIVO1,
		TELABASE,
		TELACOMBINACION,
		LOGOTIPOS,
		PARTIDA,
		TALLA
	)
	SELECT
		P.CVE_CLIENTE,
		P.CVE_PRENDA,
		P.LUGARDEENTREGA,
		P.FECHAVENCIMIENTO,
		P.PRIORIDAD,
		PIT.Partida,
		ROW_NUMBER() OVER (
        PARTITION BY P.CVE_CLIENTE, P.CVE_PRENDA, P.LUGARDEENTREGA, P.FECHAVENCIMIENTO, P.PRIORIDAD 
        ORDER BY TG.Partida
		) AS NumeroFila,
		P.TELABASE,
		P.TELACOMBINACION,
		P.LOGOTIPOS,
		TG.Partida,
		PIT.Talla
	FROM 
		PEDIDO_INTERNO PI,
		PEDIDO_INTERNO_TALLAS PIT,
		TALLAS_GENERALES TG,
		#PARTIDAS p
	WHERE 
		PI.Empresa = @EMPRESA
	AND PI.No_Pedido = @NO_PEDIDO
	AND PIT.Empresa = PI.Empresa
	AND PIT.No_Pedido = PI.No_Pedido
	AND TG.Talla = PIT.Talla
	AND P.CVE_CLIENTE = PI.Cve_Cliente
	AND P.CVE_PRENDA = PIT.Cve_Prenda
	AND P.LUGARDEENTREGA = PIT.LugarDeEntrega
	AND P.FECHAVENCIMIENTO = CONVERT(DATE,PIT.FechaVencimiento)
	AND P.PRIORIDAD = PIT.Prioridad
	GROUP BY
		P.CVE_CLIENTE,
		P.CVE_PRENDA,
		P.LUGARDEENTREGA,
		P.FECHAVENCIMIENTO,
		P.PRIORIDAD,
		PIT.Partida,
		P.TELABASE,
		P.TELACOMBINACION,
		P.LOGOTIPOS,
		TG.Partida,
		PIT.Talla
	ORDER BY
		P.CVE_CLIENTE,
		P.CVE_PRENDA,
		P.LUGARDEENTREGA,
		P.FECHAVENCIMIENTO,
		P.PRIORIDAD,
		TG.Partida

	CREATE TABLE #PEDIDO_PARTIDAS
	(
		NO_PEDIDO BIGINT,
		CVE_PRENDA NUMERIC(18,0),
		DESCRIPCIONPRENDA NVARCHAR(1000),
		TELABASE NVARCHAR(MAX),
		TELACOMBINACION NVARCHAR(MAX),
		LOGOTIPOS NVARCHAR(MAX),
		LUGARDEENTREGA NUMERIC(18,0),
		NOMBRELUGARDEENTREGA NVARCHAR(1000),
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		MOTIVOPRIORIDAD NVARCHAR(1000),
		PARTIDA BIGINT,
		TALLA NVARCHAR(50),
		CANTIDAD NUMERIC(18,0),
		PRECIO NUMERIC(18,4),
		PORCENTAJE_IVA NUMERIC(18,2),
		OBSERVACIONES_PARTIDAPRODUCCION NVARCHAR(MAX),
		OBSERVACIONES_PARTIDALOGISTICA NVARCHAR(MAX),
		OBSERVACIONES_PARTIDAFACTURACION NVARCHAR(MAX)
	)

	CREATE TABLE #PEDIDO
	(
		NO_PEDIDO BIGINT,
		CVE_PRENDA NUMERIC(18,0),
		DESCRIPCIONPRENDA NVARCHAR(1000),
		TELABASE NVARCHAR(MAX),
		TELACOMBINACION NVARCHAR(MAX),
		LOGOTIPOS NVARCHAR(MAX),
		LUGARDEENTREGA NUMERIC(18,0),
		NOMBRELUGARDEENTREGA NVARCHAR(1000),
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		MOTIVOPRIORIDAD NVARCHAR(1000),
		PARTIDA BIGINT,
		CONSECUTIVO BIGINT,
		TALLA1 NVARCHAR(50),
		TALLA2 NVARCHAR(50),
		TALLA3 NVARCHAR(50),
		TALLA4 NVARCHAR(50),
		TALLA5 NVARCHAR(50),
		TALLA6 NVARCHAR(50),
		TALLA7 NVARCHAR(50),
		TALLA8 NVARCHAR(50),
		TALLA9 NVARCHAR(50),
		TALLA10 NVARCHAR(50),
		TALLA11 NVARCHAR(50),
		TALLA12 NVARCHAR(50),
		TALLA13 NVARCHAR(50),
		PRECIO NUMERIC(18,4),
		PORCENTAJE_IVA NUMERIC(18,2),
		PRENDAS_TOTALES_PARTIDA BIGINT,
		SUBTOTAL_PARTIDA NUMERIC(18,4),
		IVA_PARTIDA NUMERIC(18,4),
		TOTAL_PARTIDA NUMERIC(18,4),
		PRENDAS_TOTALES_PEDIDO BIGINT,
		SUBTOTAL_PEDIDO NUMERIC(18,4),
		IVA_PEDIDO NUMERIC(18,4),
		TOTAL_PEDIDO NUMERIC(18,4),
		OBSERVACIONES_PARTIDAPRODUCCION NVARCHAR(MAX),
		OBSERVACIONES_PARTIDALOGISTICA NVARCHAR(MAX),
		OBSERVACIONES_PARTIDAFACTURACION NVARCHAR(MAX)
	)

	INSERT INTO #PEDIDO_PARTIDAS
	(
		NO_PEDIDO,
		CVE_PRENDA,
		DESCRIPCIONPRENDA,
		TELABASE,
		TELACOMBINACION,
		LOGOTIPOS,
		LUGARDEENTREGA,
		NOMBRELUGARDEENTREGA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		MOTIVOPRIORIDAD,
		PARTIDA,
		TALLA,
		CANTIDAD,
		PRECIO,
		PORCENTAJE_IVA,
		OBSERVACIONES_PARTIDAPRODUCCION,
		OBSERVACIONES_PARTIDALOGISTICA,
		OBSERVACIONES_PARTIDAFACTURACION
	)
	SELECT 
		PI.No_Pedido,
		PIT.Cve_Prenda,
		PIT.DescripcionPrenda,
		STUFF(
		(
			SELECT ', ' + CONVERT(NVARCHAR, PEMD.Cve_Tela) + ' (' + CT.Composicion + ')'
			FROM PRENDA_ESTRUCTURA_MATERIALES_DETALLE PEMD,CATALOGO_TELA CT
			WHERE PEMD.Cve_Prenda = PIT.Cve_Prenda AND PEMD.TipoMaterial = 'T' AND PEMD.TipoTela = 'B' AND CT.Cve_Tela = PEMD.Cve_Tela
			GROUP BY PEMD.Cve_Tela,CT.Composicion
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS TelaBase,
		STUFF(
		(
			SELECT ', ' + CONVERT(NVARCHAR, PEMD.Cve_Tela) + ' (' + CT.Composicion + ')'
			FROM PRENDA_ESTRUCTURA_MATERIALES_DETALLE PEMD,CATALOGO_TELA CT
			WHERE PEMD.Cve_Prenda = PIT.Cve_Prenda AND PEMD.TipoMaterial = 'T' AND PEMD.TipoTela = 'C' AND CT.Cve_Tela = PEMD.Cve_Tela
			GROUP BY PEMD.Cve_Tela,CT.Composicion
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS TelaCombinacion,
		STUFF(
		(
			SELECT ', ' + CONVERT(NVARCHAR, ISNULL(PL.Cve_Logotipo,'')) 
			FROM PRENDA_LOGOTIPO PL 
			WHERE PL.Cve_Prenda = PIT.Cve_Prenda
			FOR XML PATH(''), TYPE
		).value('.', 'NVARCHAR(MAX)'), 
		1, 2, ''
		) AS Logotipos,
		PIT.LugarDeEntrega,
		PIT.NombreLugarDeEntrega,
		PIT.FechaVencimiento,
		PIT.Prioridad,
		PIT.MotivoPrioridad,
		PIT.Partida,
		PIT.Talla,
		PIT.Cantidad,
		PIT.PrecioUnitario,
		PI.PorcentajeIVA,
		PIT.ObservacionesPartidaProduccion,
		PIT.ObservacionesPartidaLogistica,
		PIT.ObservacionesPartidaFacturacion
	FROM 
		PEDIDO_INTERNO PI,
		PEDIDO_INTERNO_TALLAS PIT,
		TALLAS_GENERALES TG
	WHERE 
		PI.Empresa = @EMPRESA
	AND PI.No_Pedido = @NO_PEDIDO
	AND PIT.Empresa = PI.Empresa
	AND PIT.No_Pedido = PI.No_Pedido
	AND TG.Talla = PIT.Talla

	DECLARE @sql AS NVARCHAR(MAX);

	CREATE TABLE #RELLENO
	(
		CONSECUTIVO INT,
		RELLENO NVARCHAR(100)
	)

	INSERT INTO #RELLENO VALUES(1,'[100],')
	INSERT INTO #RELLENO VALUES(2,'[100],[101],')
	INSERT INTO #RELLENO VALUES(3,'[100],[101],[102],')
	INSERT INTO #RELLENO VALUES(4,'[100],[101],[102],[103],')
	INSERT INTO #RELLENO VALUES(5,'[100],[101],[102],[103],[104],')
	INSERT INTO #RELLENO VALUES(6,'[100],[101],[102],[103],[104],[105],')
	INSERT INTO #RELLENO VALUES(7,'[100],[101],[102],[103],[104],[105],[106],')
	INSERT INTO #RELLENO VALUES(8,'[100],[101],[102],[103],[104],[105],[106],[107],')
	INSERT INTO #RELLENO VALUES(9,'[100],[101],[102],[103],[104],[105],[106],[107],[108],')
	INSERT INTO #RELLENO VALUES(10,'[100],[101],[102],[103],[104],[105],[106],[107],[108],[109],')
	INSERT INTO #RELLENO VALUES(11,'[100],[101],[102],[103],[104],[105],[106],[107],[108],[109],[110],')
	INSERT INTO #RELLENO VALUES(12,'[100],[101],[102],[103],[104],[105],[106],[107],[108],[109],[110],[111],')
	INSERT INTO #RELLENO VALUES(13,'[100],[101],[102],[103],[104],[105],[106],[107],[108],[109],[110],[111],[112],')

