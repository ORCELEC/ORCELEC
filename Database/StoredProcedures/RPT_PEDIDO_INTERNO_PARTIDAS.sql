		@CANTIDAD_DIFERENTES_TALLAS DECIMAL

	CREATE TABLE #PARTIDAS
	(
		CVE_CLIENTE BIGINT,
		CVE_PRENDA BIGINT,
		LUGARDEENTREGA BIGINT,
		PARTIDA BIGINT,
		FECHAVENCIMIENTO DATE,
		PRIORIDAD BIGINT,
		TELABASE NVARCHAR(max),
		TELACOMBINACION NVARCHAR(MAX),
		LOGOTIPOS NVARCHAR(max)
