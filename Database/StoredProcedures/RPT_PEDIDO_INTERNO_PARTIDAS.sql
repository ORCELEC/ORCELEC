	INSERT INTO #PARTIDAS
	(
		CVE_CLIENTE,
		CVE_PRENDA,
		LUGARDEENTREGA,
		PARTIDA,
		FECHAVENCIMIENTO,
		PRIORIDAD,
		TELABASE,
